// PersonalizedBox.jsx
// The CORE output of Novelty 3.
// Shows personalized explanation based on:
// - User Prakriti (from Novelty 1)
// - Fuzzy engine output
// - Age group and pregnancy status
//
// Color changes based on dominant dosha:
// Pitta = amber/orange, Vata = purple, Kapha = teal
// This visual change reinforces the personalization

export default function PersonalizedBox({
  personalized,
  prevention,
  dominantDosha
}) {

  // Background color per dominant dosha
  const bgColors = {
    pitta: "bg-amber-50 border-amber-200",
    vata: "bg-purple-50 border-purple-200",
    kapha: "bg-teal-50 border-teal-200"
  }

  // Main text color per dominant dosha
  const textColors = {
    pitta: "text-amber-900",
    vata: "text-purple-900",
    kapha: "text-teal-900"
  }

  // Title text color per dominant dosha
  const titleColors = {
    pitta: "text-amber-700",
    vata: "text-purple-700",
    kapha: "text-teal-700"
  }

  // Get colors for this user dominant dosha
  // Falls back to gray if dosha not recognized
  const bg = bgColors[dominantDosha] || "bg-gray-50 border-gray-200"
  const text = textColors[dominantDosha] || "text-gray-800"
  const title = titleColors[dominantDosha] || "text-gray-700"

  return (
    <div className={`p-4 border-t border-b ${bg}`}>

      {/* Section title showing dominant dosha */}
      <p className={`text-sm font-medium mb-2 ${title}`}>
        Personalized for you ({dominantDosha?.charAt(0).toUpperCase() + dominantDosha?.slice(1)}-dominant)
      </p>

      {/* Personalized explanation text */}
      {/* Generated by fuzzy engine + template_composer.py */}
      {/* Different for every user even with same disease */}
      <p className={`text-sm leading-relaxed mb-3 ${text}`}>
        {personalized}
      </p>

      {/* Prevention advice section */}
      {/* Only shown if prevention data exists */}
      {prevention && (
        <div className="mt-2 pt-2 border-t border-current border-opacity-20">
          <p className={`text-xs font-medium mb-1 ${title}`}>
            Prevention advice
          </p>
          {/* Prevention text personalized by dosha advice from dataset */}
          <p className={`text-xs leading-relaxed ${text}`}>
            {prevention}
          </p>
        </div>
      )}

    </div>
  )
}